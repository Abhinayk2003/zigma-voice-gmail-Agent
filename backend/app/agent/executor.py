# =============================================================
# Automatic generated-email note
# =============================================================

AUTO_REPLY_NOTE = (
    "Note: This email is automatically generated by computer."
)


class GmailExecutor:
    """
    Executes structured Gmail intents.

    The executor does NOT understand natural language.

    Natural-language understanding is performed by Bedrock
    before this class is called.

    Responsibilities
    ----------------
    - Execute structured Gmail operations.
    - Resolve semantic message references through
      ConversationState.
    - Preserve conversational context.
    - Remember sent and replied messages.
    - Use Gmail-generated message/thread/draft IDs.
    - Never generate Gmail IDs.
    - Never accept user-specific Gmail identifiers as
      application-generated values.
    - Require confirmation before destructive actions.

    Architecture
    ------------

        User language
             |
             v
        Bedrock / AI planner
             |
             v
        GmailIntentRequest
             |
             v
        GmailExecutor
             |
             v
        ConversationState
             |
             v
        Gmail services
             |
             v
        Gmail API

    Responsibilities by layer
    --------------------------

    Bedrock:
        Decides WHAT the user wants.

    ConversationState:
        Decides WHICH Gmail message/thread the user
        is referring to.

    GmailExecutor:
        Executes the structured operation.

    Gmail:
        Supplies actual:
            - message_id
            - thread_id
            - draft_id

    No user-specific Gmail information is hard-coded.
    """

    # =========================================================
    # INITIALIZATION
    # =========================================================

    def __init__(
        self,
        state: ConversationState | None = None,
    ) -> None:
        """
        Initialize the Gmail executor.

        A shared ConversationState instance is preferred so
        conversational context survives across requests.
        """

        self.state = (
            state
            if state is not None
            else conversation_state
        )

    # =========================================================
    # PUBLIC EXECUTE
    # =========================================================

    def execute(
        self,
        request: GmailIntentRequest,
        account_email: str | None = None,
    ) -> dict[str, Any]:
        """
        Execute a structured Gmail request.

        Parameters
        ----------
        request:
            Structured Gmail intent produced by the intent layer.

        account_email:
            Authenticated Gmail account supplied by the
            authentication/session layer.

        The LLM does not control the authenticated Gmail
        account.
        """

        # -----------------------------------------------------
        # Validate request
        # -----------------------------------------------------

        if not isinstance(
            request,
            GmailIntentRequest,
        ):
            raise TypeError(
                "request must be a GmailIntentRequest."
            )

        # -----------------------------------------------------
        # Store authenticated account
        # -----------------------------------------------------

        if account_email:

            cleaned_account = account_email.strip()

            if not cleaned_account:

                raise ValueError(
                    "Authenticated Gmail account cannot be empty."
                )

            self.state.set_account(
                cleaned_account
            )

        # -----------------------------------------------------
        # Resolve account
        # -----------------------------------------------------

        account = (
            account_email
            or self.state.account_email
        )

        if account:
            account = account.strip()

        if not account:

            raise ValueError(
                "Authenticated Gmail account is required."
            )

        # -----------------------------------------------------
        # Intent dispatch
        # -----------------------------------------------------

        handlers = {
            GmailIntent.SEARCH: self._search,
            GmailIntent.READ: self._read,
            GmailIntent.SEND: self._send,
            GmailIntent.DRAFT: self._draft,
            GmailIntent.REPLY: self._reply,
            GmailIntent.STAR: self._star,
            GmailIntent.UNSTAR: self._unstar,
            GmailIntent.DELETE: self._delete,
            GmailIntent.MARK_READ: self._mark_read,
            GmailIntent.MARK_UNREAD: self._mark_unread,
            GmailIntent.LIST_UNREAD: self._list_unread,
            GmailIntent.THREAD: self._thread,
        }

        handler = handlers.get(
            request.intent
        )

        if handler is None:

            raise ValueError(
                "Unsupported Gmail intent: "
                f"{request.intent.value}"
            )

        return handler(
            request=request,
            account_email=account,
        )

    # =========================================================
    # SEARCH
    # =========================================================

    def _search(
        self,
        request: GmailIntentRequest,
        account_email: str,
    ) -> dict[str, Any]:
        """
        Search or list Gmail messages.

        Query, result limit and account are resolved dynamically.
        """

        # -----------------------------------------------------
        # Resolve query
        # -----------------------------------------------------

        query = (
            request.query.strip()
            if request.query
            else None
        )

        # -----------------------------------------------------
        # Resolve result limit
        # -----------------------------------------------------

        max_results = (
            request.max_results
            if request.max_results is not None
            else None
        )

        if max_results is not None:

            if max_results <= 0:

                raise ValueError(
                    "max_results must be greater than zero."
                )

        # -----------------------------------------------------
        # Execute search
        # -----------------------------------------------------

        if query:

            result = gmail_read_service.search(
                account_email=account_email,
                query=query,
                max_results=max_results,
            )

        else:

            result = gmail_read_service.list_messages(
                account_email=account_email,
                query=None,
                max_results=max_results,
            )

        # -----------------------------------------------------
        # Extract results
        # -----------------------------------------------------

        messages = (
            result.get(
                "messages",
                [],
            )
            or []
        )

        next_page_token = result.get(
            "next_page_token"
        )

        # -----------------------------------------------------
        # Store results in conversation state
        # -----------------------------------------------------

        self.state.set_results(
            messages=messages,
            query=query,
            next_page_token=next_page_token,
        )

        # -----------------------------------------------------
        # Record action
        # -----------------------------------------------------

        self.state.record_action(
            action="search",
            details={
                "query": query,
                "result_count": len(messages),
            },
        )

        # -----------------------------------------------------
        # Return result
        # -----------------------------------------------------

        return {
            "success": True,
            "intent": GmailIntent.SEARCH.value,
            "query": query,
            "count": len(messages),
            "messages": messages,
            "next_page_token": next_page_token,
            "page": self.state.current_page,
        }

    # =========================================================
    # LIST UNREAD
    # =========================================================

    def _list_unread(
        self,
        request: GmailIntentRequest,
        account_email: str,
    ) -> dict[str, Any]:
        """
        List unread Gmail messages.

        The unread filter is represented using the standard
        Gmail search query:

            is:unread

        This method does not hard-code:
            - account
            - sender
            - recipient
            - subject
            - message ID
            - thread ID

        The query itself is an application-level semantic
        operation corresponding to the LIST_UNREAD intent.
        """

        # -----------------------------------------------------
        # Resolve result limit dynamically
        # -----------------------------------------------------

        max_results = (
            request.max_results
            if request.max_results is not None
            else None
        )

        if max_results is not None:

            if max_results <= 0:

                raise ValueError(
                    "max_results must be greater than zero."
                )

        # -----------------------------------------------------
        # Gmail unread query
        # -----------------------------------------------------

        query = "is:unread"

        # -----------------------------------------------------
        # Execute unread search
        # -----------------------------------------------------

        result = gmail_read_service.search(
            account_email=account_email,
            query=query,
            max_results=max_results,
        )

        # -----------------------------------------------------
        # Extract messages
        # -----------------------------------------------------

        messages = (
            result.get(
                "messages",
                [],
            )
            or []
        )

        next_page_token = result.get(
            "next_page_token"
        )

        # -----------------------------------------------------
        # Store unread results in conversation state
        # -----------------------------------------------------

        self.state.set_results(
            messages=messages,
            query=query,
            next_page_token=next_page_token,
        )

        # -----------------------------------------------------
        # Record action
        # -----------------------------------------------------

        self.state.record_action(
            action="list_unread",
            details={
                "query": query,
                "result_count": len(messages),
            },
        )

        # -----------------------------------------------------
        # Return result
        # -----------------------------------------------------

        return {
            "success": True,
            "intent": GmailIntent.LIST_UNREAD.value,
            "query": query,
            "count": len(messages),
            "messages": messages,
            "next_page_token": next_page_token,
            "page": self.state.current_page,
        }

    # =========================================================
    # READ
    # =========================================================

    def _read(
        self,
        request: GmailIntentRequest,
        account_email: str,
    ) -> dict[str, Any]:
        """
        Read a dynamically resolved Gmail message.
        """

        # -----------------------------------------------------
        # Resolve target message
        # -----------------------------------------------------

        result = self._resolve_message(
            request,
            account_email=account_email,
        )

        # -----------------------------------------------------
        # Retrieve complete Gmail message
        # -----------------------------------------------------

        message = gmail_read_service.get_message(
            account_email=account_email,
            message_id=result.message_id,
        )

        # -----------------------------------------------------
        # Make message current
        # -----------------------------------------------------

        self._select_result_object(
            result,
            message_data=message,
        )

        # -----------------------------------------------------
        # Record action
        # -----------------------------------------------------

        self.state.record_action(
            action="read",
            details={
                "message_id": result.message_id,
                "thread_id": result.thread_id,
            },
        )

        return {
            "success": True,
            "intent": GmailIntent.READ.value,
            "message": message,
            "message_id": result.message_id,
            "thread_id": result.thread_id,
        }

    # =========================================================
    # SEND
    # =========================================================

    def _send(
        self,
        request: GmailIntentRequest,
        account_email: str,
    ) -> dict[str, Any]:
        """
        Send a new Gmail message.

        Recipient, subject and body come from the structured
        request.

        Gmail generates message_id and thread_id.
        """

        # -----------------------------------------------------
        # Validate recipient
        # -----------------------------------------------------

        if not request.recipient:

            raise ValueError(
                "Recipient email address is required."
            )

        recipient = request.recipient.strip()

        if not recipient:

            raise ValueError(
                "Recipient email address is required."
            )

        # -----------------------------------------------------
        # Validate subject
        # -----------------------------------------------------

        if not request.subject:

            raise ValueError(
                "Email subject is required."
            )

        subject = request.subject.strip()

        if not subject:

            raise ValueError(
                "Email subject is required."
            )

        # -----------------------------------------------------
        # Validate body
        # -----------------------------------------------------

        if not request.body:

            raise ValueError(
                "Email body is required."
            )

        body = request.body.strip()

        if not body:

            raise ValueError(
                "Email body is required."
            )

        # -----------------------------------------------------
        # Add automatic generation note
        # -----------------------------------------------------

        send_body = (
            body.rstrip()
            + "\n\n"
            + AUTO_REPLY_NOTE
        )

        # -----------------------------------------------------
        # Preserve current Gmail context
        # -----------------------------------------------------

        self._preserve_current_context()

        # -----------------------------------------------------
        # Send email
        # -----------------------------------------------------

        result = gmail_send_service.send_email(
            account_email=account_email,
            recipient=recipient,
            subject=subject,
            body=send_body,
            cc=request.cc,
            bcc=request.bcc,
        )

        # -----------------------------------------------------
        # Gmail-generated identifiers
        # -----------------------------------------------------

        message_id = result.get(
            "message_id"
        )

        thread_id = result.get(
            "thread_id"
        )

        # -----------------------------------------------------
        # Store sent message context
        # -----------------------------------------------------

        self._set_generated_message_context(
            message_id=message_id,
            thread_id=thread_id,
            subject=subject,
            recipient=recipient,
            body=send_body,
            action="send",
            data=result,
        )

        # -----------------------------------------------------
        # Remember sent message
        # -----------------------------------------------------

        if message_id:

            self.state.remember_sent_message(
                message_id=message_id,
                thread_id=thread_id,
                recipient=recipient,
                subject=subject,
                body=send_body,
            )

        # -----------------------------------------------------
        # Record action
        # -----------------------------------------------------

        self.state.record_action(
            action="send",
            details={
                "message_id": message_id,
                "thread_id": thread_id,
                "recipient": recipient,
                "subject": subject,
            },
        )

        return {
            "success": True,
            "intent": GmailIntent.SEND.value,
            **result,
        }

