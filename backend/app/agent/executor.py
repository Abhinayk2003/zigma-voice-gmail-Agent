    # =========================================================
    # RESOLVE LATEST MESSAGE
    # =========================================================

    def _resolve_latest_message(
        self,
        account_email: str,
    ) -> GmailResult:
        """
        Resolve the latest email dynamically.

        Resolution order:

            1. Existing conversational result.
            2. Dynamically query Gmail for latest message.
        """

        # -----------------------------------------------------
        # Prefer current conversational result
        # -----------------------------------------------------

        latest = self.state.get_latest_result()

        if latest:
            return latest

        # -----------------------------------------------------
        # Query Gmail dynamically
        # -----------------------------------------------------

        response = gmail_read_service.list_messages(
            account_email=account_email,
            query=None,
            max_results=1,
        )

        messages = (
            response.get(
                "messages",
                [],
            )
            or []
        )

        if not messages:

            raise ValueError(
                "There is no email available."
            )

        # -----------------------------------------------------
        # Store retrieved message
        # -----------------------------------------------------

        self.state.set_results(
            messages=messages,
            query=None,
            next_page_token=response.get(
                "next_page_token"
            ),
        )

        # -----------------------------------------------------
        # Resolve latest from state
        # -----------------------------------------------------

        latest = self.state.get_latest_result()

        if not latest:

            raise ValueError(
                "Gmail returned an email but it could "
                "not be stored in conversation state."
            )

        return latest

    # =========================================================
    # RESOLVE MESSAGE
    # =========================================================

    def _resolve_message(
        self,
        request: GmailIntentRequest,
        account_email: str | None = None,
    ) -> GmailResult:
        """
        Resolve a semantic Gmail message reference.

        Supported reference types include:

            POSITION
            CURRENT
            PREVIOUS
            LATEST
            RAW / generic semantic reference

        Gmail IDs are never generated by this method.
        """

        reference = getattr(
            request,
            "message_reference",
            None,
        )

        account = (
            account_email
            or self.state.account_email
        )

        if account:
            account = account.strip()

        # =====================================================
        # No message reference object
        # =====================================================

        if reference is None:

            return self.state.resolve_message()

        # =====================================================
        # POSITION
        # =====================================================

        if (
            reference.type
            == MessageReferenceType.POSITION
        ):

            if reference.position is None:

                raise ValueError(
                    "Message position is missing."
                )

            position = reference.position

            if position <= 0:

                raise ValueError(
                    "Message position must be greater than zero."
                )

            if not account:

                raise ValueError(
                    "Authenticated Gmail account is required."
                )

            # -------------------------------------------------
            # Load enough messages if state is empty
            # -------------------------------------------------

            if not self.state.current_results:

                response = gmail_read_service.list_messages(
                    account_email=account,
                    query=None,
                    max_results=position,
                )

                messages = (
                    response.get(
                        "messages",
                        [],
                    )
                    or []
                )

                if not messages:

                    raise ValueError(
                        "There are no emails available."
                    )

                if len(messages) < position:

                    raise ValueError(
                        f"Only {len(messages)} email(s) "
                        "are available for the requested position."
                    )

                self.state.set_results(
                    messages=messages,
                    query=None,
                    next_page_token=response.get(
                        "next_page_token"
                    ),
                )

            return self.state.resolve_message(
                position=position
            )

        # =====================================================
        # CURRENT
        # =====================================================

        if (
            reference.type
            == MessageReferenceType.CURRENT
        ):

            return self.state.resolve_message(
                reference="current"
            )

        # =====================================================
        # PREVIOUS
        # =====================================================

        if (
            reference.type
            == MessageReferenceType.PREVIOUS
        ):

            return self.state.resolve_message(
                reference="previous"
            )

        # =====================================================
        # LATEST
        # =====================================================

        if (
            reference.type
            == MessageReferenceType.LATEST
        ):

            if not account:

                raise ValueError(
                    "Authenticated Gmail account is required."
                )

            try:

                return self.state.resolve_message(
                    reference="latest"
                )

            except ValueError:

                return self._resolve_latest_message(
                    account_email=account
                )

        # =====================================================
        # GENERIC / RAW REFERENCE
        # =====================================================

        raw_reference = getattr(
            reference,
            "raw",
            None,
        )

        if not raw_reference:

            return self.state.resolve_message()

        return self.state.resolve_message(
            reference=raw_reference
        )

    # =========================================================
    # RESOLVE THREAD MESSAGE
    # =========================================================

    def _resolve_thread_message(
        self,
        request: GmailIntentRequest,
        account_email: str | None = None,
    ) -> GmailResult:
        """
        Resolve the Gmail message whose thread should be opened.

        Thread IDs always come from Gmail/state.
        """

        # -----------------------------------------------------
        # Explicit thread reference
        # -----------------------------------------------------

        thread_reference = getattr(
            request,
            "thread_reference",
            None,
        )

        if (
            thread_reference is not None
            and thread_reference.is_present()
        ):

            temporary_request = GmailIntentRequest(
                intent=GmailIntent.THREAD,
                message_reference=thread_reference,
            )

            return self._resolve_message(
                temporary_request,
                account_email=account_email,
            )

        # -----------------------------------------------------
        # Message reference identifies the thread
        # -----------------------------------------------------

        message_reference = getattr(
            request,
            "message_reference",
            None,
        )

        if (
            message_reference is not None
            and message_reference.is_present()
        ):

            return self._resolve_message(
                request,
                account_email=account_email,
            )

        # -----------------------------------------------------
        # Otherwise use current selection
        # -----------------------------------------------------

        return self.state.resolve_message()

    # =========================================================
    # PRESERVE CURRENT CONTEXT
    # =========================================================

    def _preserve_current_context(
        self,
    ) -> None:
        """
        Preserve the current Gmail selection before an operation
        changes conversational context.
        """

        # -----------------------------------------------------
        # Prefer complete current message context
        # -----------------------------------------------------

        if self.state.current_message_context:

            self.state.previous_message_context = (
                dict(
                    self.state.current_message_context
                )
            )

            self.state.previous_message_id = (
                self.state.current_message_context.get(
                    "message_id"
                )
            )

            self.state.previous_thread_id = (
                self.state.current_message_context.get(
                    "thread_id"
                )
            )

        # -----------------------------------------------------
        # Fallback to selected identifiers
        # -----------------------------------------------------

        elif self.state.selected_message_id:

            self.state.previous_message_id = (
                self.state.selected_message_id
            )

            self.state.previous_thread_id = (
                self.state.selected_thread_id
            )

    # =========================================================
    # SET GENERATED MESSAGE CONTEXT
    # =========================================================

    def _set_generated_message_context(
        self,
        message_id: str | None,
        thread_id: str | None,
        subject: str | None = None,
        recipient: str | None = None,
        body: str | None = None,
        action: str = "select",
        data: dict[str, Any] | None = None,
    ) -> None:
        """
        Store a Gmail-generated message as current context.

        Used after:

            - SEND
            - DRAFT
            - REPLY

        Gmail supplies the actual identifiers.
        """

        # -----------------------------------------------------
        # Gmail must provide message ID
        # -----------------------------------------------------

        if not message_id:
            return

        # -----------------------------------------------------
        # Set selected identifiers
        # -----------------------------------------------------

        self.state.selected_message_id = (
            message_id
        )

        if thread_id:

            self.state.selected_thread_id = (
                thread_id
            )

        # -----------------------------------------------------
        # Build conversational context
        # -----------------------------------------------------

        context: dict[str, Any] = {
            "message_id":
                message_id,

            "thread_id":
                thread_id,

            "subject":
                subject,

            "sender":
                None,

            "recipient":
                recipient,

            "snippet":
                None,

            "date":
                None,

            "body":
                body or "",

            "action":
                action,

            "data":
                dict(data)
                if isinstance(
                    data,
                    dict,
                )
                else {},
        }

        # -----------------------------------------------------
        # Store current context
        # -----------------------------------------------------

        self.state.current_message_context = (
            context
        )

        # -----------------------------------------------------
        # Store latest action
        # -----------------------------------------------------

        self.state.last_action = action

    # =========================================================
    # SELECT RESULT OBJECT
    # =========================================================

    def _select_result_object(
        self,
        result: GmailResult,
        message_data: dict[str, Any] | None = None,
    ) -> None:
        """
        Make a Gmail result the current conversational selection.

        This preserves previous context and stores the selected
        message as current context.
        """

        # -----------------------------------------------------
        # Validate result
        # -----------------------------------------------------

        if not result:

            raise ValueError(
                "A Gmail result is required for selection."
            )

        if not result.message_id:

            raise ValueError(
                "A valid Gmail message is required for selection."
            )

        # -----------------------------------------------------
        # Preserve existing context
        # -----------------------------------------------------

        self._preserve_current_context()

        # -----------------------------------------------------
        # Set current selected message
        # -----------------------------------------------------

        self.state.selected_message_id = (
            result.message_id
        )

        self.state.selected_thread_id = (
            result.thread_id
        )

        # -----------------------------------------------------
        # Build combined message data
        # -----------------------------------------------------

        data: dict[str, Any] = {}

        if isinstance(
            result.data,
            dict,
        ):

            data.update(
                result.data
            )

        if isinstance(
            message_data,
            dict,
        ):

            data.update(
                message_data
            )

        # -----------------------------------------------------
        # Store complete conversational context
        # -----------------------------------------------------

        self.state.current_message_context = {
            "message_id":
                result.message_id,

            "thread_id":
                result.thread_id,

            "subject":
                result.subject,

            "sender":
                result.sender,

            "recipient":
                result.recipient,

            "snippet":
                result.snippet,

            "date":
                result.date,

            "body":
                ConversationState._extract_body(
                    data
                ),

            "action":
                "select",

            "data":
                dict(data),
        }

        # -----------------------------------------------------
        # Remember latest action
        # -----------------------------------------------------

        self.state.last_action = (
            "select_email"
        )


