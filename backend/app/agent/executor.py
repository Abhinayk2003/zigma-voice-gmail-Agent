    # =========================================================
    # DELETE
    # =========================================================

    def _delete(
        self,
        request: GmailIntentRequest,
        account_email: str,
    ) -> dict[str, Any]:
        """
        Prepare a delete operation.

        The message is NOT deleted immediately.

        The resolved Gmail message is stored as a pending
        destructive operation.
        """

        # -----------------------------------------------------
        # Resolve target message
        # -----------------------------------------------------

        result = self._resolve_message(
            request,
            account_email=account_email,
        )

        # -----------------------------------------------------
        # Make selected message current
        # -----------------------------------------------------

        self._select_result_object(
            result
        )

        # -----------------------------------------------------
        # Store pending delete
        # -----------------------------------------------------

        self.state.set_pending_delete(
            result=result,
            account_email=account_email,
        )

        # -----------------------------------------------------
        # Record confirmation requirement
        # -----------------------------------------------------

        self.state.record_action(
            action="delete_confirmation_required",
            details={
                "message_id":
                    result.message_id,

                "thread_id":
                    result.thread_id,

                "position":
                    result.position,

                "subject":
                    result.subject,

                "sender":
                    result.sender,
            },
        )

        # -----------------------------------------------------
        # Return confirmation request
        # -----------------------------------------------------

        return {
            "success": True,
            "intent": GmailIntent.DELETE.value,
            "confirmation_required": True,

            "message_id":
                result.message_id,

            "thread_id":
                result.thread_id,

            "position":
                result.position,

            "subject":
                result.subject,

            "sender":
                result.sender,
        }

    # =========================================================
    # CONFIRM PENDING DELETE
    # =========================================================

    def confirm_pending_delete(
        self,
        account_email: str | None = None,
    ) -> dict[str, Any]:
        """
        Execute a delete operation that was previously prepared.

        The message ID comes only from ConversationState.
        """

        # -----------------------------------------------------
        # Retrieve pending action
        # -----------------------------------------------------

        pending = (
            self.state.get_pending_action()
        )

        if not pending:

            raise ValueError(
                "There is no Gmail delete operation "
                "awaiting confirmation."
            )

        # -----------------------------------------------------
        # Verify pending action
        # -----------------------------------------------------

        if pending.get("action") != "delete":

            raise ValueError(
                "The pending operation is not "
                "a delete operation."
            )

        # -----------------------------------------------------
        # Resolve authenticated account
        # -----------------------------------------------------

        pending_account = pending.get(
            "account_email"
        )

        account = (
            account_email
            or pending_account
            or self.state.account_email
        )

        if account:
            account = account.strip()

        if not account:

            raise ValueError(
                "Authenticated Gmail account is required."
            )

        # -----------------------------------------------------
        # Resolve pending Gmail message ID
        # -----------------------------------------------------

        message_id = pending.get(
            "message_id"
        )

        if not message_id:

            self.state.clear_pending_action()

            raise ValueError(
                "The pending Gmail message "
                "could not be resolved."
            )

        thread_id = pending.get(
            "thread_id"
        )

        # -----------------------------------------------------
        # Execute Gmail trash operation
        # -----------------------------------------------------

        response = gmail_read_service.delete_message(
            account_email=account,
            message_id=message_id,
        )

        # -----------------------------------------------------
        # Clear pending operation
        # -----------------------------------------------------

        self.state.clear_pending_action()

        # -----------------------------------------------------
        # Record completed delete
        # -----------------------------------------------------

        self.state.record_action(
            action="delete",
            details={
                "message_id":
                    message_id,

                "thread_id":
                    thread_id,

                "subject":
                    pending.get(
                        "subject"
                    ),

                "sender":
                    pending.get(
                        "sender"
                    ),
            },
        )

        # -----------------------------------------------------
        # Return result
        # -----------------------------------------------------

        return {
            "success": True,
            "intent": GmailIntent.DELETE.value,
            "confirmation_required": False,

            "message_id":
                message_id,

            "thread_id":
                thread_id,

            "subject":
                pending.get(
                    "subject"
                ),

            "sender":
                pending.get(
                    "sender"
                ),

            **response,
        }

